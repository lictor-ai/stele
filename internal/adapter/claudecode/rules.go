package claudecode

import (
	"bytes"
	_ "embed"
	"strings"
	"text/template"

	"github.com/lictor-ai/stele/internal/adapter"
	"github.com/lictor-ai/stele/internal/rulesblock"
)

// RulesFile is where stele writes the project's rules for Claude Code to load
// (#68), relative to a root, in slash form. With no paths: frontmatter,
// Claude Code loads a file in .claude/rules/ at launch, as it loads CLAUDE.md:
// whole, with none of the 10,000-character cap on a hook's text, again after
// a resume or a compaction, and in each subagent. It is not named stele.md:
// a directory holding a stele.md is a stele root.
const RulesFile = ".claude/rules/stele-rules.md"

// MaxRulesFile caps a read of RulesFile. stele.md is capped at 4 MiB; its
// rules rendered with their scopes stay well under this.
const MaxRulesFile = 16 << 20

// rulesFile is the file's text. It is a file, not a string in the code: it is
// what the agent reads before its first prompt.
//
//go:embed assets/rules-file.tmpl
var rulesFile string

var rulesTemplate = template.Must(template.New("rules-file").Funcs(template.FuncMap{
	"join": func(s []string) string { return strings.Join(s, ", ") },
}).Parse(rulesFile))

// RenderRules returns the file for rules, in their order. A rule whose id
// cannot be a marker is left out, and stays covered by the hook's deny.
func RenderRules(rules []adapter.Rule) []byte {
	var keep []adapter.Rule
	for _, r := range rules {
		if rulesblock.ValidID(r.ID) {
			keep = append(keep, r)
		}
	}
	var b bytes.Buffer
	if err := rulesTemplate.Execute(&b, keep); err != nil {
		panic(err) // the template is compiled in and tested
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n')
}

// RuleHash is the hash ReadRules gives r's block in a file RenderRules wrote.
// It is "" when the block would not read back as r alone, such as a body
// holding a marker line, or when r holds an HTML comment's opening or closing:
// Claude Code may hide comments when it loads the file, and an unclosed one
// could hide the rest of the rule from the agent. Such a rule is never taken
// as read.
func RuleHash(r adapter.Rule) string {
	for _, s := range append([]string{r.Body}, r.Scope...) {
		if strings.Contains(s, "<!--") || strings.Contains(s, "-->") {
			return ""
		}
	}
	var b bytes.Buffer
	if err := rulesTemplate.ExecuteTemplate(&b, "block", r); err != nil {
		panic(err)
	}
	got := ReadRules(b.Bytes())
	if len(got) != 1 {
		return ""
	}
	return got[r.ID]
}

// header opens every file RenderRules writes, whatever its version: the
// file is stele's only when it starts so.
const header = "<!-- Generated by stele"

// MaxRulesChars is the size past which a rules file is worth a warning:
// every session loads it whole, and Claude Code flags memory files of about
// this many characters.
const MaxRulesChars = 40000

// OwnedRules reports whether data is a rules file stele wrote: its first
// line, a byte order mark aside, opens with the generated header. stele never
// overwrites or removes a file that does not.
func OwnedRules(data []byte) bool {
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))
	first, _, _ := strings.Cut(string(data), "\n")
	return strings.HasPrefix(first, header)
}

// SameRules reports whether the file on disk gives the agent the same rules,
// in the same order, as want: the header and intro text may differ, so a
// stele of another version does not rewrite a committed file for its words
// alone. A change to a block's format still changes its hash.
func SameRules(disk, want []byte) bool {
	return OwnedRules(disk) && rulesblock.Same(disk, want)
}

// ReadRules returns the rules in a file as the agent read it: rule id to a
// hash of its block's text (rulesblock.Read).
func ReadRules(data []byte) map[string]string { return rulesblock.Read(data) }
