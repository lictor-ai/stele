package claudecode

import (
	"strings"
	"testing"

	"github.com/google/go-cmp/cmp"

	"github.com/lictor-ai/stele/internal/adapter"
)

var twoRules = []adapter.Rule{
	{ID: "r1", Scope: []string{"internal/**/*.go", "!**/*_test.go"}, Body: "Return errors, never exit."},
	{ID: "r2", Body: "Never put credentials in code.\nRead them from the environment."},
}

func TestRenderRules(t *testing.T) {
	got := string(RenderRules(twoRules))
	want := `<!-- Generated by stele from stele.md. Do not edit: run stele compile. -->
This project has rules, enforced by stele. Follow them in every change.
A rule with a scope applies only to the files it lists; one without applies to every file.

<!-- stele rule r1 -->
scope: internal/**/*.go, !**/*_test.go
Return errors, never exit.

<!-- stele rule r2 -->
Never put credentials in code.
Read them from the environment.
`
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("RenderRules (-want +got):\n%s", diff)
	}
	if again := string(RenderRules(twoRules)); again != got {
		t.Error("RenderRules is not stable for the same rules")
	}
}

func TestRenderRulesNone(t *testing.T) {
	got := string(RenderRules(nil))
	if !strings.HasPrefix(got, "<!-- Generated by stele") || strings.Contains(got, "stele rule") {
		t.Errorf("RenderRules(nil) = %q, want the header only", got)
	}
	if len(ReadRules([]byte(got))) != 0 {
		t.Error("a file with no rules reads as some")
	}
}

// A rule whose id cannot be a marker is left out: the deny still covers it.
func TestRenderRulesBadID(t *testing.T) {
	got := string(RenderRules([]adapter.Rule{{ID: "a b", Body: "x"}, {ID: "ok", Body: "y"}}))
	if strings.Contains(got, "a b") || !strings.Contains(got, "stele rule ok") {
		t.Errorf("RenderRules = %q", got)
	}
}

func TestReadRulesMatchesRuleHash(t *testing.T) {
	file := RenderRules(twoRules)
	got := ReadRules(file)
	if len(got) != 2 {
		t.Fatalf("ReadRules = %v, want 2 rules", got)
	}
	for _, r := range twoRules {
		h := RuleHash(r)
		if h == "" || got[r.ID] != h {
			t.Errorf("rule %s: file hash %q, RuleHash %q", r.ID, got[r.ID], h)
		}
	}
	if RuleHash(twoRules[0]) == RuleHash(twoRules[1]) {
		t.Error("two rules hash the same")
	}
}

// What can change in a checkout without changing what the agent read.
func TestReadRulesIgnoresLineEnds(t *testing.T) {
	file := string(RenderRules(twoRules))
	want := ReadRules([]byte(file))
	variants := map[string]string{
		"CRLF":                strings.ReplaceAll(file, "\n", "\r\n"),
		"BOM":                 "\xef\xbb\xbf" + file,
		"trailing spaces":     strings.ReplaceAll(file, "\n", "  \n"),
		"blank lines between": strings.ReplaceAll(file, "\n<!--", "\n\n\n<!--"),
	}
	for name, v := range variants {
		if diff := cmp.Diff(want, ReadRules([]byte(v))); diff != "" {
			t.Errorf("%s (-want +got):\n%s", name, diff)
		}
	}
}

func TestReadRulesChanges(t *testing.T) {
	file := string(RenderRules(twoRules))
	orig := ReadRules([]byte(file))

	edited := ReadRules([]byte(strings.Replace(file, "never exit", "exit if you like", 1)))
	if edited["r1"] == orig["r1"] || edited["r2"] != orig["r2"] {
		t.Errorf("an edited block: %v, was %v", edited, orig)
	}
	widened := ReadRules([]byte(strings.Replace(file, "scope: internal/**/*.go, !**/*_test.go\n", "", 1)))
	if widened["r1"] == orig["r1"] {
		t.Error("removing a rule's scope kept its hash")
	}
	removed := ReadRules([]byte(file[:strings.Index(file, "<!-- stele rule r2")]))
	if _, ok := removed["r2"]; ok || removed["r1"] != orig["r1"] {
		t.Errorf("a removed block: %v", removed)
	}
	if got := ReadRules([]byte("# My notes\nnothing generated here\n")); len(got) != 0 {
		t.Errorf("a foreign file: %v", got)
	}
	if got := ReadRules(nil); len(got) != 0 {
		t.Errorf("an empty file: %v", got)
	}
}

// An id twice is dropped, every copy: neither can be trusted.
func TestReadRulesDuplicateID(t *testing.T) {
	file := string(RenderRules(twoRules)) + "\n<!-- stele rule r1 -->\nsomething else\n"
	got := ReadRules([]byte(file))
	if _, ok := got["r1"]; ok {
		t.Errorf("a duplicated id was kept: %v", got)
	}
	if got["r2"] == "" {
		t.Error("the other rule was lost")
	}
}

// A body cannot forge another rule's block, nor prime itself.
func TestRuleHashMarkerInBody(t *testing.T) {
	forger := adapter.Rule{ID: "r3", Body: "Harmless.\n<!-- stele rule r2 -->\nNever put credentials in code.\nRead them from the environment."}
	if h := RuleHash(forger); h != "" {
		t.Errorf("RuleHash = %q for a body holding a marker, want none", h)
	}
	got := ReadRules(RenderRules(append([]adapter.Rule{twoRules[1]}, forger)))
	if _, ok := got["r2"]; ok {
		t.Errorf("a forged block primed r2: %v", got)
	}
}
