// The rules file stele compile writes (#68) goes with the hooks; the user's
// other rules stay.
func TestUninstallRemovesTheRulesFile(t *testing.T) {
	root := t.TempDir()
	if _, _, err := Init(cc, root, "v1.0.0", Set{}); err != nil {
		t.Fatal(err)
	}
	rules := filepath.Join(root, filepath.FromSlash(cc.RulesFile()))
	mine := filepath.Join(root, ".claude", "rules", "mine.md")
	write(t, rules, "<!-- Generated by stele -->\n")
	write(t, mine, "mine")

	changes, _, err := Uninstall(cc, root)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"removed stele hooks from " + cc.SettingsFile(), "removed " + cc.RulesFile(), "removed .stele/"}
	if diff := cmp.Diff(want, changes); diff != "" {
		t.Errorf("changes mismatch (-want +got):\n%s", diff)
	}
	if exists(rules) || !exists(mine) {
		t.Errorf("rules file kept, or the user's rule removed")
	}

	// With nothing else there, .claude/rules/ and .claude/ go too.
	root = t.TempDir()
	if _, _, err := Init(cc, root, "v1.0.0", Set{}); err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(root, filepath.FromSlash(cc.RulesFile())), "<!-- Generated by stele -->\nx\n")
	if _, _, err := Uninstall(cc, root); err != nil {
		t.Fatal(err)
	}
	if exists(filepath.Join(root, ".claude")) {
		t.Errorf(".claude/ is still there")
	}
}

// A file there without stele's header is the user's: left, with a note.
func TestUninstallLeavesARulesFileNotSteles(t *testing.T) {
	root := t.TempDir()
	if _, _, err := Init(cc, root, "v1.0.0", Set{}); err != nil {
		t.Fatal(err)
	}
	rules := filepath.Join(root, filepath.FromSlash(cc.RulesFile()))
	write(t, rules, "# Our own rules\n")
	changes, notes, err := Uninstall(cc, root)
	if err != nil {
		t.Fatal(err)
	}
	if read(t, rules) != "# Our own rules\n" {
		t.Error("the user's file was removed")
	}
	for _, c := range changes {
		if c == "removed "+cc.RulesFile() {
			t.Errorf("changes = %q", changes)
		}
	}
	if len(notes) != 1 || notes[0] != cc.RulesFile()+" is not stele's: left it" {
		t.Errorf("notes = %q", notes)
	}
}

func TestUninstallRefusesALinkedRulesDir(t *testing.T) {
	if runtime.GOOS != "windows" {
		t.Skip("junctions are Windows only")
	}
	root := t.TempDir()
	if _, _, err := Init(cc, root, "v1.0.0", Set{}); err != nil {
		t.Fatal(err)
	}
	outside := t.TempDir()
	keep := filepath.Join(outside, "stele-rules.md")
	write(t, keep, "keep")
	if out, err := exec.Command("cmd", "/c", "mklink", "/J", filepath.Join(root, ".claude", "rules"), outside).CombinedOutput(); err != nil {
		t.Skipf("mklink /J: %v: %s", err, out)
	}
	settings := filepath.Join(root, cc.SettingsFile())
	before := read(t, settings)
	if _, _, err := Uninstall(cc, root); err == nil {
		t.Error("Uninstall went through a linked .claude/rules")
	}
	if !exists(keep) || read(t, settings) != before {
		t.Error("something was removed")
	}
}
