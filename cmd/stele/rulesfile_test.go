package main

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/lictor-ai/stele/internal/adapter/claudecode"
	"github.com/lictor-ai/stele/internal/check"
)

// rulesFile is the rules file under root.
func rulesFile(root string) string {
	return filepath.Join(root, filepath.FromSlash(claudecode.RulesFile))
}

func TestCompileWritesTheRulesFile(t *testing.T) {
	root := project(t, rules)
	if code, _, errOut := runCmd("compile"); code != exitOK {
		t.Fatalf("compile = %d, stderr %q", code, errOut)
	}
	data, err := os.ReadFile(rulesFile(root))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"Generated by stele", "<!-- stele rule ", "Never build SQL", "Every handler goes through"} {
		if !strings.Contains(string(data), want) {
			t.Errorf("rules file lacks %q:\n%s", want, data)
		}
	}
	if got := len(claudecode.ReadRules(data)); got != 2 {
		t.Errorf("rules file holds %d rules, want 2", got)
	}
}

func TestCheckRulesFile(t *testing.T) {
	const stale = ".claude/rules/stele-rules.md is out of date with the rules: run stele compile and commit .claude/rules/stele-rules.md"
	cases := []struct {
		name   string
		mutate func(path string) error
		code   int
	}{
		{"current", func(string) error { return nil }, exitOK},
		{"stale", func(p string) error { return os.WriteFile(p, []byte("old rules\n"), 0o644) }, exitFailed},
		{"missing", os.Remove, exitFailed},
		{"CRLF", func(p string) error {
			data, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			return os.WriteFile(p, []byte(strings.ReplaceAll(string(data), "\n", "\r\n")), 0o644)
		}, exitOK},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := gitProject(t, checkRules)
			if err := tc.mutate(rulesFile(root)); err != nil {
				t.Fatal(err)
			}
			code, _, errOut := runCmd("check", "--all")
			if code != tc.code {
				t.Fatalf("check = %d, stderr %q, want %d", code, errOut, tc.code)
			}
			if tc.code == exitFailed && !strings.Contains(errOut, stale) {
				t.Errorf("stderr = %q, want %q", errOut, stale)
			}

			code, out, _ := runCmd("check", "--all", "--format", "json")
			if code != tc.code {
				t.Fatalf("check --format json = %d, want %d", code, tc.code)
			}
			if tc.code == exitFailed {
				var rep check.Report
				if err := json.Unmarshal([]byte(out), &rep); err != nil {
					t.Fatalf("stdout is not JSON: %q", out)
				}
				if len(rep.Problems) != 1 || rep.Problems[0].Message != stale {
					t.Errorf("problems = %+v", rep.Problems)
				}
			}
		})
	}
}

// The rules file holds every rule's text, so a rule's pattern quoted in its
// own body must not flag it.
func TestCheckSkipsTheRulesFile(t *testing.T) {
	gitProject(t, checkRules)
	code, out, errOut := runCmd("check", ".claude/rules/stele-rules.md")
	if code != exitOK || strings.Contains(out, "stele-rules.md:") {
		t.Errorf("check = %d, stdout %q, stderr %q: the rules file was checked", code, out, errOut)
	}
}
