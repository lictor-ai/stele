const notOurs = ".claude/rules/stele-rules.md is not stele's: rename it, then run stele compile"

// A user's own file at the rules file's path is never overwritten.
func TestRulesFileNotStelesIsLeftAlone(t *testing.T) {
	root := gitProject(t, checkRules)
	mine := "# My notes on our rules\n"
	if err := os.WriteFile(rulesFile(root), []byte(mine), 0o644); err != nil {
		t.Fatal(err)
	}

	code, _, errOut := runCmd("compile")
	if code != exitOK || !strings.Contains(errOut, notOurs) {
		t.Errorf("compile = %d, stderr %q, want a note %q", code, errOut, notOurs)
	}
	if code, _, errOut := runCmd("check", "--all"); code != exitFailed || !strings.Contains(errOut, notOurs) {
		t.Errorf("check = %d, stderr %q", code, errOut)
	}
	if o, _ := hook(t, write(filepath.Join(root, "a.go"), "p1", "")); o.SystemMessage != "" {
		t.Errorf("the hook warned: %q", o.SystemMessage)
	}
	if data, _ := os.ReadFile(rulesFile(root)); string(data) != mine {
		t.Errorf("the file was replaced: %q", data)
	}

	if code, out, errOut := runCmd("uninstall"); code != exitOK || strings.Contains(out, "removed .claude/rules") || !strings.Contains(errOut, "not stele's") {
		t.Errorf("uninstall = %d, stdout %q, stderr %q", code, out, errOut)
	}
	if data, _ := os.ReadFile(rulesFile(root)); string(data) != mine {
		t.Errorf("uninstall removed it: %q", data)
	}
}

func TestInitLeavesARulesFileNotStelesAlone(t *testing.T) {
	root := project(t, "")
	if err := os.MkdirAll(filepath.Dir(rulesFile(root)), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(rulesFile(root), []byte("mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	code, out, errOut := runCmd("init")
	if code != exitOK || strings.Contains(out, "wrote .claude/rules") || !strings.Contains(errOut, notOurs) {
		t.Errorf("init = %d, stdout %q, stderr %q", code, out, errOut)
	}
	if data, _ := os.ReadFile(rulesFile(root)); string(data) != "mine\n" {
		t.Errorf("init replaced it: %q", data)
	}
}

// Every session loads the whole file: say so when it is large.
func TestRulesFileSizeWarning(t *testing.T) {
	big := strings.Repeat("Keep functions short and their names clear, and write a test for each.\n", 600) // ~42,000 characters
	root := gitProject(t, big)
	_ = root
	const warn = "every session loads it"
	code, _, errOut := runCmd("compile")
	if code != exitOK || !strings.Contains(errOut, warn) || !strings.Contains(errOut, "characters") {
		t.Errorf("compile = %d, stderr %q, want a size note", code, errOut)
	}
	if code, _, errOut := runCmd("check", "--all"); code != exitOK || !strings.Contains(errOut, warn) {
		t.Errorf("check = %d, stderr %q, want a size note and exit 0", code, errOut)
	}

	gitProject(t, checkRules)
	if _, _, errOut := runCmd("check", "--all"); strings.Contains(errOut, warn) {
		t.Errorf("a small file was warned about: %q", errOut)
	}
}

// Refreshing a stale rules file on the hook's path is a skip when it cannot
// be done at once: no wait, no warning.
func TestHookRefreshIsBestEffort(t *testing.T) {
	clock(t, time.Now())
	root := gitProject(t, hookRules)

	t.Run("lock held", func(t *testing.T) {
		if err := os.WriteFile(rulesFile(root), []byte("<!-- Generated by stele -->\nstale\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		unlock, err := safefile.Lock(filepath.Join(root, index.Dir, "compile.lock"), time.Second, 30*time.Second)
		if err != nil {
			t.Fatal(err)
		}
		defer unlock()
		start := time.Now()
		o, _ := hook(t, write(filepath.Join(root, "a.go"), "p1", ""))
		if o.SystemMessage != "" {
			t.Errorf("warning %q with the compile lock held", o.SystemMessage)
		}
		if d := time.Since(start); d > time.Second {
			t.Errorf("the hook took %v", d)
		}
	})

	t.Run("read-only file", func(t *testing.T) {
		if runtime.GOOS != "windows" {
			t.Skip("read-only blocks a replace only on Windows")
		}
		if err := os.WriteFile(rulesFile(root), []byte("<!-- Generated by stele -->\nstale\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.Chmod(rulesFile(root), 0o444); err != nil {
			t.Skipf("cannot make it read-only: %v", err)
		}
		t.Cleanup(func() { os.Chmod(rulesFile(root), 0o644) })
		start := time.Now()
		o, _ := hook(t, write(filepath.Join(root, "b.go"), "p2", ""))
		if o.SystemMessage != "" {
			t.Errorf("warning %q on a read-only file", o.SystemMessage)
		}
		if d := time.Since(start); d > 200*time.Millisecond {
			t.Errorf("the hook took %v on a read-only stale file", d)
		}
	})
}
